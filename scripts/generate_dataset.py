"""Generic labeled-data generator for the small paper problems (QCQP, MIMO, IK).

Driven entirely by problems/registry.py's ProblemSpec, so this one script
replaces the four problem-specific generate_*_data.py scripts for the unified
workflow. AC-OPF is NOT handled here -- its data already exists under
data/acopf-hpc/ (generated by the SAVIO-specific generate_acopf_data_parallel.py)
and is reused as-is; see registry.get_spec's can_generate=False flag.

Writes:
    <train_csv>  columns: features..., Cost, Exact
    <test_csv>   columns: features..., Cost, Exact, LocalCost
    results/<key>/solve_times.json  {mean_relax_solve_s, mean_local_solve_s, n_...}

Optionally parallelizes across instances with multiprocessing -- IK's order-2
Lasserre relaxation (~1-5s/solve) is the case this matters for; QCQP/MIMO/IK-lass1
are fast enough to run serially in seconds either way.

Usage:
    python scripts/generate_dataset.py --key qcqp
    python scripts/generate_dataset.py --key ik_lass2 --n-workers 8
    python scripts/generate_dataset.py --key ik_lass2 --limit 20   # local smoke test
"""

import argparse
import json
import pathlib
import sys
import time

import numpy as np
import pandas as pd

PROJECT_ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from problems.registry import get_spec, SMALL_PROBLEM_KEYS

# ── per-worker state (built once per process, matching the ACOPF parallel
#    generator's pattern) ───────────────────────────────────────────────────
_W_spec = None
_W_relax_args = None
_W_local_args = None


def _worker_init(key, n_train, n_test):
    global _W_spec, _W_relax_args, _W_local_args
    _W_spec = get_spec(key, n_train=n_train, n_test=n_test)
    _W_relax_args = _W_spec.build_relax_args(_W_spec.default_args)
    _W_local_args = dict(_W_spec.default_args)


def _label_one(task):
    """Label a single parameter vector. Returns (idx, relax_value, exact,
    relax_seconds, local_value, local_seconds). local fields are NaN when
    include_local is False (train split doesn't need the local solve).

    Any solver exception is caught and recorded as NaN rather than propagating
    -- one bad instance must not take down the whole (possibly hours-long) run.
    """
    idx, p, include_local = task
    t0 = time.perf_counter()
    try:
        val, res = _W_spec.solve_relax(p, args=_W_relax_args)
        exact = bool(res.get("exact", False))
    except Exception:
        val, exact = np.nan, False
    relax_s = time.perf_counter() - t0

    local_val, local_s = np.nan, np.nan
    if include_local:
        t0 = time.perf_counter()
        try:
            local_val, _ = _W_spec.solve_local(p, args=_W_local_args)
        except Exception:
            local_val = np.nan
        local_s = time.perf_counter() - t0

    return idx, float(val), exact, relax_s, float(local_val), local_s


def _label_split(spec, P, include_local, n_workers, n_train, n_test):
    """Label every row of P, sequentially or via a multiprocessing.Pool.

    n_train/n_test are only used to reconstruct the ProblemSpec inside each
    worker process (get_spec needs them to build path fields, even though this
    function only touches the solver callables) -- they don't affect labeling.
    """
    tasks = [(i, P[i], include_local) for i in range(len(P))]
    n = len(tasks)
    results = [None] * n

    if n_workers <= 1:
        _worker_init(spec.key, n_train, n_test)
        for t in tasks:
            i, *rest = _label_one(t)
            results[i] = rest
    else:
        import multiprocessing as mp
        with mp.Pool(processes=n_workers, initializer=_worker_init,
                     initargs=(spec.key, n_train, n_test)) as pool:
            for i, *rest in pool.imap_unordered(_label_one, tasks, chunksize=max(1, n // (4 * n_workers))):
                results[i] = rest

    return results


def generate(key, n_train, n_test, n_workers, limit, seed_train, seed_test):
    spec = get_spec(key, n_train=n_train, n_test=n_test)
    if not spec.can_generate:
        raise ValueError(f"'{key}' is a reuse-only config (e.g. AC-OPF); "
                          f"its data is not regenerated by this script.")

    n_tr = limit or n_train
    n_te = limit or n_test

    print(f"[{key}] sampling {n_tr} train + {n_te} test instances "
          f"(n_workers={n_workers})", flush=True)

    P_train = spec.sample_parameters(n_tr, args=dict(spec.default_args, seed=seed_train))
    P_test = spec.sample_parameters(n_te, args=dict(spec.default_args, seed=seed_test))

    t0 = time.time()
    train_rows = _label_split(spec, P_train, include_local=False, n_workers=n_workers,
                               n_train=n_train, n_test=n_test)
    print(f"  train labeled in {time.time()-t0:.1f}s", flush=True)

    t0 = time.time()
    test_rows = _label_split(spec, P_test, include_local=True, n_workers=n_workers,
                              n_train=n_train, n_test=n_test)
    print(f"  test labeled in {time.time()-t0:.1f}s", flush=True)

    feat_cols = spec.feature_cols
    train_df = pd.DataFrame(P_train, columns=feat_cols)
    train_df["Cost"] = [r[0] for r in train_rows]
    train_df["Exact"] = [r[1] for r in train_rows]

    test_df = pd.DataFrame(P_test, columns=feat_cols)
    test_df["Cost"] = [r[0] for r in test_rows]
    test_df["Exact"] = [r[1] for r in test_rows]
    test_df["LocalCost"] = [r[3] for r in test_rows]

    spec.train_csv.parent.mkdir(parents=True, exist_ok=True)
    spec.test_csv.parent.mkdir(parents=True, exist_ok=True)
    train_df.to_csv(spec.train_csv, index=False)
    test_df.to_csv(spec.test_csv, index=False)
    print(f"  wrote {spec.train_csv} ({len(train_df)} rows)")
    print(f"  wrote {spec.test_csv} ({len(test_df)} rows)")

    # Step 2: average solve times, over both splits' relaxation solves and the
    # test split's local solves (train split skips the local solve entirely).
    relax_times = [r[2] for r in train_rows] + [r[2] for r in test_rows]
    local_times = [r[4] for r in test_rows]
    relax_times = [t for t in relax_times if np.isfinite(t)]
    local_times = [t for t in local_times if np.isfinite(t)]

    timing = {
        "key": key,
        "n_relax_solves": len(relax_times),
        "mean_relax_solve_s": float(np.mean(relax_times)) if relax_times else float("nan"),
        "n_local_solves": len(local_times),
        "mean_local_solve_s": float(np.mean(local_times)) if local_times else float("nan"),
    }
    spec.results_dir.mkdir(parents=True, exist_ok=True)
    timing_path = spec.results_dir / "solve_times.json"
    with open(timing_path, "w") as fh:
        json.dump(timing, fh, indent=2)
    print(f"  wrote {timing_path}: {timing}")

    n_train_feasible = int(np.isfinite(train_df["Cost"]).sum())
    n_test_feasible = int(np.isfinite(test_df["Cost"]).sum())
    print(f"  feasible: train {n_train_feasible}/{len(train_df)}, "
          f"test {n_test_feasible}/{len(test_df)}")


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--key", required=True, choices=SMALL_PROBLEM_KEYS)
    p.add_argument("--n-train", type=int, default=20_000)
    p.add_argument("--n-test", type=int, default=5_000)
    p.add_argument("--n-workers", type=int, default=1,
                   help="multiprocessing pool size; 1 = serial (default)")
    p.add_argument("--limit", type=int, default=None,
                   help="override n-train/n-test with a small count for a local smoke test")
    p.add_argument("--seed-train", type=int, default=0)
    p.add_argument("--seed-test", type=int, default=1)
    args = p.parse_args()

    generate(args.key, args.n_train, args.n_test, args.n_workers, args.limit,
             args.seed_train, args.seed_test)


if __name__ == "__main__":
    main()
